#!/usr/bin/env bash
# One-time local setup. Safe to run again: existing files are kept.
# Creates .env, the JWT RSA key pair in secrets/, a locally trusted TLS certificate in certs/
# and downloads the Neo4j Graph Data Science jar into plugins/.
set -euo pipefail

cd "$(dirname "$0")/.."

# Must match the neo4j image in docker-compose.yml (5.26.33 -> GDS 2.13.15, see https://graphdatascience.ninja/versions.json)
GDS_VERSION=2.13.15

for tool in docker mkcert openssl curl; do
  if ! command -v "$tool" >/dev/null 2>&1; then
    echo "missing: $tool" >&2
    case "$tool" in
      mkcert) echo "  install: sudo apt install mkcert libnss3-tools   (or: brew install mkcert)" >&2 ;;
      docker) echo "  install: https://docs.docker.com/engine/install/" >&2 ;;
      openssl) echo "  install: sudo apt install openssl" >&2 ;;
      curl) echo "  install: sudo apt install curl" >&2 ;;
    esac
    exit 1
  fi
done

# 1. .env with random values
if [ -f .env ]; then
  echo ".env exists, kept"
else
  NEO4J_PASSWORD="$(openssl rand -base64 24 | tr -d '/+=')"
  TOTP_ENC_KEY="$(openssl rand -base64 32)"
  cat > .env <<EOF
NEO4J_PASSWORD=${NEO4J_PASSWORD}
TOTP_ENC_KEY=${TOTP_ENC_KEY}
EOF
  chmod 600 .env
  echo ".env created"
fi

# 2. RSA 2048 key pair for JWT RS256 (user-service signs, the others verify)
mkdir -p secrets
if [ -f secrets/jwt-private.pem ] && [ -f secrets/jwt-public.pem ]; then
  echo "secrets/jwt-*.pem exist, kept"
else
  openssl genpkey -algorithm RSA -pkeyopt rsa_keygen_bits:2048 -out secrets/jwt-private.pem 2>/dev/null
  openssl pkey -in secrets/jwt-private.pem -pubout -out secrets/jwt-public.pem
  echo "secrets/jwt-private.pem and secrets/jwt-public.pem created"
fi

# 3. Locally trusted certificate for https://localhost (mkcert installs a local CA in the OS and browser stores)
mkdir -p certs
if [ -f certs/cert.pem ] && [ -f certs/key.pem ]; then
  echo "certs/cert.pem and certs/key.pem exist, kept"
else
  mkcert -install
  mkcert -cert-file certs/cert.pem -key-file certs/key.pem localhost 127.0.0.1 ::1
  echo "certs/cert.pem and certs/key.pem created"
fi

# 4. Neo4j Graph Data Science jar, downloaded once and bind mounted into the neo4j container.
# (The image's NEO4J_PLUGINS mechanism re-downloads the 65 MB jar on every container start.)
mkdir -p plugins
if [ -f plugins/graph-data-science.jar ]; then
  echo "plugins/graph-data-science.jar exists, kept"
else
  curl -fsSL -o plugins/graph-data-science.jar "https://graphdatascience.ninja/neo4j-graph-data-science-${GDS_VERSION}.jar"
  echo "plugins/graph-data-science.jar (GDS ${GDS_VERSION}) downloaded"
fi

# 5. Permissions. These files are bind mounted read-only into containers that run as non-root
# (neo4j uid 7474, nginx uid 101, Java services uid 1001). A bind mount keeps the host owner, so
# the container uid can only read them if they are world readable. The private keys are per-machine
# demo material, regenerated by this script and gitignored, so 644 is accepted here.
# Enterprise version: Docker Swarm or Kubernetes secrets, which mount with a chosen uid and mode.
chmod 755 secrets certs plugins
chmod 644 secrets/jwt-private.pem secrets/jwt-public.pem certs/cert.pem certs/key.pem plugins/graph-data-science.jar

echo
echo "Setup done. Next:"
echo "  docker compose up --build"
